'use strict';
const assert=require('node:assert/strict');
const E=require('./engine.js');
const W=E.world;
const find=id=>Object.values(W.encounters).flat().find(e=>e.id===id);
const preview=(s,id,key)=>E.choiceExplanation(s,find(id),find(id).choices.find(c=>c.id===key),'en');
const s=E.fresh();
let p=preview(s,'forest:1','fight');
assert.match(p.risk,/leads to death/);
assert.match(p.benefit,/no rewards or progression/);
s.body=100;s.realm=5;p=preview(s,'forest:1','fight');
assert.match(p.risk,/enough power to win/);
assert.match(p.benefit,/If victorious/);
p=preview(s,'forest:sen-second-chance','lin');
assert.match(p.intent,/Tell Lin/);assert.doesNotMatch(p.intent,/payment|supplies/);
p=preview(s,'village:mei-caravan','accept');
assert.match(p.intent,/payment follows delivery/);
assert.doesNotMatch(p.benefit,/22 coins/);
s.cultivation.learned.stance={rank:1,progress:0};s.stamina=1;s.body=0;
p=preview(s,'village:ren-balance','carry');
assert.match(p.cost,/up to 1 stamina/);assert.match(p.benefit,/practice \+10/);
s.cultivation.learned.stance.progress=E.techniqueNeeded(1);
p=preview(s,'village:ren-balance','carry');
assert.doesNotMatch(p.cost,/technique movements/);assert.match(p.benefit,/will not increase/);
assert.match(p.requirement,/Body/);
console.log('PASS: deterministic danger, honest promises, bounded movement practice and actual requirements');
