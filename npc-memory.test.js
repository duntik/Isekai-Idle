const assert=require('node:assert/strict');
const M=require('./npc-memory.js');
const s={stage:0,world:{people:M.fresh()}};
assert.equal(M.people(s).length,0);
M.recordMeeting(s,{id:'forest:0'});
assert.equal(M.people(s,'en')[0].name,'Lin');
assert.equal(s.world.people.lin.trust,0);
assert.equal(M.recordChoice(s,{id:'forest:0'},{id:'learn',mentor:'herbalist'}),true);
assert.equal(M.recordChoice(s,{id:'forest:0'},{id:'learn',mentor:'herbalist'}),false);
assert.equal(s.world.people.lin.trust,1);
M.recordChoice(s,{id:'forest:lin-clinic'},{id:'later',skip:true});
assert.equal(s.world.people.lin.trust,1);
assert.match(M.context(s,{id:'forest:lin-clinic'},'en'),/postponed/);
M.recordChoice(s,{id:'forest:lin-clinic'},{id:'prepare'},'failure');
assert.equal(s.world.people.lin.trust,1);
assert.match(M.context(s,{id:'forest:lin-clinic'},'en'),/failed/);
M.recordChoice(s,{id:'forest:lin-clinic'},{id:'prepare'});
assert.equal(s.world.people.lin.trust,2);
const gen={id:'village:generated:0:1:0:weather'};
M.recordMeeting(s,gen);
M.recordChoice(s,gen,{id:'labor',route:'help'});
assert.equal(M.people(s,'en').find(x=>x.id==='local:village:1').name,'Carpenter Shu');
assert.match(M.context(s,{id:'village:generated:0:1:3:raiders'},'en'),/helped/);
const legacy={storyStep:1,stage:0,world:{mentors:['scholar'],director:{decisions:{'forest:0/learn':true}}}};
assert.deepEqual(M.validate(null,legacy),M.validate(null,legacy));
assert.ok(M.validate(null,legacy).wei);
assert.ok(M.validate(null,legacy).mei);
assert.ok(M.validate(null,legacy).lin);
assert.deepEqual(M.validate(JSON.parse(JSON.stringify(s.world.people))),s.world.people);
const bad=M.validate({bogus:{trust:99},ren:{trust:Infinity,memories:[{key:'bad',kind:'bogus'}]}});
assert.equal(bad.bogus,undefined);
assert.equal(bad.ren.trust,10);
for(const p of M.people(s,'en'))assert.doesNotMatch(JSON.stringify(p),/[А-Яа-яЁё]/);
console.log('NPC memory tests passed.');
const previewState={stage:0,world:{people:{},seed:123}};
const previewScene={id:'forest:lin-clinic'};
const beforePreview=JSON.stringify(previewState);
const promise=M.preview(previewState,previewScene,{id:'letter',contact:'letter'},'en');
assert.equal(promise.kind,'promise');
assert.equal(promise.trust,1);
assert.match(promise.text,/still needs to be completed/);
assert.equal(JSON.stringify(previewState),beforePreview);
assert.equal(M.preview(previewState,previewScene,{id:'prepare',memory:{trust:0}},'en').trust,0);
assert.equal(M.preview(previewState,previewScene,{id:'prepare',memory:{trust:2}},'en','failure').trust,0);
assert.equal(M.preview(previewState,previewScene,{id:'later',memory:{kind:'help',trust:2}},'en').trust,0);
assert.equal(M.preview(previewState,previewScene,{id:'prepare',skip:true,memory:{kind:'help',trust:2}},'en').trust,0);
M.recordChoice(previewState,previewScene,{id:'prepare'});
const repeat=M.preview(previewState,previewScene,{id:'prepare'},'en');
assert.equal(repeat.first,false);
assert.equal(repeat.trust,0);
assert.match(repeat.text,/not awarded twice/);
previewState.world.people.lin.trust=10;
assert.equal(M.preview(previewState,previewScene,{id:'different',route:'help'},'en').trust,0);
assert.equal(M.preview(previewState,{id:'unknown'},{id:'help'}),null);
assert.doesNotMatch(JSON.stringify(promise),/[А-Яа-яЁё]/);
